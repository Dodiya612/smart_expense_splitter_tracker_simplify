def format_settlement_response(
    settlement: Settlement,
    is_partial: bool = False,
    remaining_debt_paise: int | None = None,
) -> SettlementResponse:
    """Format a Settlement ORM entity into a SettlementResponse DTO."""
    return SettlementResponse(
        id=settlement.id,
        group_id=settlement.group_id,
        payer_id=settlement.payer_id,
        payee_id=settlement.payee_id,
        amount_paise=settlement.amount_paise,
        status=settlement.status,
        payment_method=settlement.payment_method,
        notes=settlement.notes,
        settlement_date=settlement.settlement_date,
        is_partial=is_partial,
        remaining_debt_paise=remaining_debt_paise,
        created_at=settlement.created_at,
        updated_at=settlement.updated_at,
    )


async def get_group_settlement_context(
    db: AsyncSession,
    group_id: uuid.UUID,
) -> tuple[dict[str, int], list[Expense], list[Settlement]]:
    """Retrieve all expenses and settlements for a group and compute net positions.

    Integrates with the pure ledger engine net_positions() function.
    """
    # 1. Fetch all non-deleted shared expenses for this group
    exp_res = await db.execute(
        select(Expense)
        .options(
            selectinload(Expense.payments),
            selectinload(Expense.shares),
        )
        .where(
            Expense.group_id == group_id,
            Expense.deleted_at.is_(None),
        )
    )
    expenses = list(exp_res.scalars().all())

    # 2. Fetch all completed settlements for this group
    stl_res = await db.execute(
        select(Settlement)
        .where(
            Settlement.group_id == group_id,
            Settlement.status == "completed",
        )
        .order_by(Settlement.created_at.asc())
    )
    settlements = list(stl_res.scalars().all())

    # 3. Convert to ledger records
    expense_records: list[ExpenseRecord] = []
    for exp in expenses:
        payments = {str(p.user_id): p.amount_paise for p in exp.payments}
        shares = {str(s.user_id): s.amount_paise for s in exp.shares}
        expense_records.append(
            ExpenseRecord(
                expense_id=str(exp.id),
                description=exp.description,
                amount_paise=exp.amount_minor,
                payments=payments,
                shares=shares,
            )
        )

    settlement_records: list[SettlementRecord] = [
        SettlementRecord(
            settlement_id=str(stl.id),
            from_user=str(stl.payer_id),
            to_user=str(stl.payee_id),
            amount_paise=stl.amount_paise,
        )
        for stl in settlements
    ]

    # 4. Pure deterministic ledger calculation
    balances = net_positions(expense_records, settlement_records)
    return balances, expenses, settlements


async def calculate_group_balances(
    db: AsyncSession,
    group_id: uuid.UUID,
    current_user: User,
) -> GroupBalancesResponse:
    """Calculate dynamic member balances and simplified repayment suggestions.

    Guarantees:
    - Zero-sum conservation: sum of net balances is 0.
    - Deterministic creditor and debtor categorization.
    - Minimal repayment transactions generated by greedy simplification.
    """
    group = await get_group_or_404(db, group_id)
    check_group_membership(group, current_user, require_admin=False)

    balances, _, _ = await get_group_settlement_context(db, group_id)

    # Include all active members even if their balance is zero
    active_member_ids = {
        m.user_id for m in group.members if m.status == GroupMemberStatus.ACTIVE.value
    }
    # Ensure every active member is represented in balances
    for uid in active_member_ids:
        if str(uid) not in balances:
            balances[str(uid)] = 0

    member_items: list[MemberBalanceItem] = []
    debtor_items: list[DebtorCreditorSummary] = []
    creditor_items: list[DebtorCreditorSummary] = []

    for uid_str, bal in sorted(balances.items()):
        uid = uuid.UUID(uid_str)
        if bal > 0:
            status_str = "creditor"
            owes = 0
            receives = bal
            creditor_items.append(DebtorCreditorSummary(user_id=uid, amount_paise=bal))
        elif bal < 0:
            status_str = "debtor"
            owes = -bal
            receives = 0
            debtor_items.append(DebtorCreditorSummary(user_id=uid, amount_paise=-bal))
        else:
            status_str = "settled"
            owes = 0
            receives = 0

        member_items.append(
            MemberBalanceItem(
                user_id=uid,
                net_balance_paise=bal,
                owes_paise=owes,
                receives_paise=receives,
                status=status_str,
            )
        )

    # Simplified repayment suggestions
    transfers = simplify(balances)
    suggested_transfers_data = [t.model_dump() for t in transfers]

    total_debt = sum(c.amount_paise for c in creditor_items)

    return GroupBalancesResponse(
        group_id=group_id,
        net_positions=balances,
        suggested_transfers=suggested_transfers_data,
        members=member_items,
        debtors=debtor_items,
        creditors=creditor_items,
        total_debt_paise=total_debt,
        currency="INR",
    )


async def calculate_simplified_repayments(
    db: AsyncSession,
    group_id: uuid.UUID,
    current_user: User,
) -> SimplifiedRepaymentsResponse:
    """Derive simplified repayment transactions for a group."""
    group = await get_group_or_404(db, group_id)
    check_group_membership(group, current_user, require_admin=False)

    balances, _, _ = await get_group_settlement_context(db, group_id)
    transfers = simplify(balances)
    transfer_dicts = [t.model_dump() for t in transfers]
    total_amount = sum(t["amount_paise"] for t in transfer_dicts)

    return SimplifiedRepaymentsResponse(
        group_id=group_id,
        suggested_transfers=transfer_dicts,
        total_transfers=len(transfer_dicts),
        total_amount_paise=total_amount,
    )


async def create_settlement(
    db: AsyncSession,
    group_id: uuid.UUID,
    current_user: User,
    payload: SettlementCreateRequest,
) -> SettlementResponse:
    """Record a full or partial settlement between two group members atomically.

    Validations:
    - Group existence and caller membership.
    - Payer and payee must be active group members and distinct users.
    - Caller must be either payer, payee, or a group admin.
    - Payer must have an outstanding debt (net_position < 0).
    - Payee must be owed money (net_position > 0).
    - Payment cannot exceed outstanding obligation (min(|NP_payer|, NP_payee)).
    - Atomic persistence with audit logging.
    """
    group = await get_group_or_404(db, group_id)
    caller_member = check_group_membership(group, current_user, require_admin=False)

    payer_id = payload.payer_id
    payee_id = payload.payee_id

    if payer_id == payee_id:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail={
                "code": "SELF_SETTLEMENT_PROHIBITED",
                "message": "Payer and payee cannot be the same member.",
            },
        )

    # Verify both payer and payee are active group members
    active_members = {
        m.user_id: m for m in group.members if m.status == GroupMemberStatus.ACTIVE.value
    }
    if payer_id not in active_members:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail={
                "code": "PAYER_NOT_IN_GROUP",
                "message": "Payer is not an active member of this group.",
            },
        )
    if payee_id not in active_members:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail={
                "code": "PAYEE_NOT_IN_GROUP",
                "message": "Payee is not an active member of this group.",
            },
        )

    # Authorization check: only payer, payee, or group admin can record settlement
    is_admin = caller_member.role == GroupMemberRole.ADMIN.value
    if current_user.id != payer_id and current_user.id != payee_id and not is_admin:
        raise HTTPException(
            status_code=status.HTTP_403_FORBIDDEN,
            detail={
                "code": "UNAUTHORIZED_SETTLEMENT_RECORDING",
                "message": "Only the payer, the payee, or a group admin may record this settlement.",
            },
        )

    # Calculate current balances including previous settlements
    balances, _, _ = await get_group_settlement_context(db, group_id)

    payer_bal = balances.get(str(payer_id), 0)
    payee_bal = balances.get(str(payee_id), 0)

    if payer_bal >= 0:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail={
                "code": "PAYER_NOT_DEBTOR",
                "message": f"Payer does not have an outstanding debt in this group (net balance: {payer_bal} paise).",
            },
        )

    if payee_bal <= 0:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail={
                "code": "PAYEE_NOT_CREDITOR",
                "message": f"Payee is not owed any money in this group (net balance: {payee_bal} paise).",
            },
        )

    # Maximum amount that can be settled between this debtor and creditor
    max_outstanding = min(abs(payer_bal), payee_bal)

    if payload.is_full_settlement and payload.amount_paise is None:
        settlement_amount = max_outstanding
    else:
        settlement_amount = payload.amount_paise

    if settlement_amount is None or settlement_amount <= 0:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail={
                "code": "INVALID_SETTLEMENT_AMOUNT",
                "message": "Settlement amount must be strictly greater than zero paise.",
            },
        )

    if settlement_amount > max_outstanding:
        raise HTTPException(
            status_code=status.HTTP_400_BAD_REQUEST,
            detail={
                "code": "AMOUNT_EXCEEDS_OUTSTANDING",
                "message": (
                    f"Settlement amount ({settlement_amount} paise) exceeds outstanding debt "
                    f"between payer and payee ({max_outstanding} paise)."
                ),
            },
        )

    is_partial = settlement_amount < max_outstanding
    remaining_debt = max_outstanding - settlement_amount

    # Atomic persistence
    settlement = Settlement(
        group_id=group_id,
        payer_id=payer_id,
        payee_id=payee_id,
        amount_paise=settlement_amount,
        status="completed",
        payment_method=payload.payment_method,
        notes=payload.notes,
        settlement_date=payload.settlement_date or datetime.now(UTC).date(),
    )

    try:
        db.add(settlement)
        await db.flush()

        audit_snapshot = {
            "group_id": str(group_id),
            "payer_id": str(payer_id),
            "payee_id": str(payee_id),
            "amount_paise": settlement_amount,
            "is_partial": is_partial,
            "remaining_debt_paise": remaining_debt,
        }
        audit_event = AuditEvent(
            actor_id=current_user.id,
            entity_type="settlement",
            entity_id=settlement.id,
            action="settlement_created",
            before_after=json.dumps(audit_snapshot),
        )
        db.add(audit_event)

        await db.commit()
    except Exception:
        await db.rollback()
        raise

    return format_settlement_response(
        settlement,
        is_partial=is_partial,
        remaining_debt_paise=remaining_debt,
    )


async def list_settlements(
    db: AsyncSession,
    group_id: uuid.UUID,
    current_user: User,
) -> list[SettlementResponse]:
    """List all settlement records for a group in reverse chronological order."""
    group = await get_group_or_404(db, group_id)
    check_group_membership(group, current_user, require_admin=False)

    result = await db.execute(
        select(Settlement)
        .where(Settlement.group_id == group_id)
        .order_by(Settlement.settlement_date.desc(), Settlement.created_at.desc())
    )
    settlements = list(result.scalars().all())
    return [format_settlement_response(s) for s in settlements]


async def get_settlement(
    db: AsyncSession,
    group_id: uuid.UUID,
    settlement_id: uuid.UUID,
    current_user: User,
) -> SettlementResponse:
    """Retrieve details of a specific settlement record."""
    group = await get_group_or_404(db, group_id)
    check_group_membership(group, current_user, require_admin=False)

    result = await db.execute(
        select(Settlement).where(
            Settlement.id == settlement_id,
            Settlement.group_id == group_id,
        )
    )
    settlement = result.scalars().first()
    if not settlement:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail={
                "code": "SETTLEMENT_NOT_FOUND",
                "message": "Settlement record not found.",
            },
        )
    return format_settlement_response(settlement)
