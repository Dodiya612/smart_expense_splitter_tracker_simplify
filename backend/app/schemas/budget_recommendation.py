"""Budget recommendation schemas (US-25 / T-55).

Advisory-only schemas for AI goal setting and budget recommendations.
Uses integer paise for all monetary values and supports 0%, 5%, 10% savings levels.
"""

from __future__ import annotations

import uuid
from typing import Any

from pydantic import ConfigDict, Field, field_validator

from app.schemas.common import BaseSchema, to_camel


class _StrictSchema(BaseSchema):
    model_config = ConfigDict(
        alias_generator=to_camel,
        populate_by_name=True,
        from_attributes=True,
        extra="forbid",
    )


class BudgetRecommendationRequest(_StrictSchema):
    """Request payload for budget goal recommendation.
    
    Omit ``category_id`` for an overall budget recommendation.
    ``savings_level_percent`` must be 0, 5, or 10.
    """

    category_id: uuid.UUID | None = Field(
        None, description="Category to recommend budget for; omit for overall budget."
    )
    savings_level_percent: int = Field(
        10, description="Target savings deduction percentage: 0, 5, or 10."
    )

    @field_validator("savings_level_percent")
    @classmethod
    def _validate_savings_level(cls, v: int) -> int:
        if v not in (0, 5, 10):
            raise ValueError("savings_level_percent must be 0, 5, or 10")
        return v


class HistoricalMonthSpend(_StrictSchema):
    """Spending figures for a single completed historical calendar month."""

    month: str = Field(..., description="Calendar month in YYYY-MM format.")
    spent_paise: int = Field(..., description="Total user share spent in paise before trimming.")
    spike_paise: int = Field(..., description="Amount of trimmed one-off spikes in paise.")
    net_paise: int = Field(..., description="Trimmed spending in paise (spent - spike).")


class BudgetRecommendationResponse(_StrictSchema):
    """Transparent calculation figures and explanation for a recommended budget."""

    category_id: uuid.UUID | None = Field(
        None, description="Category UUID if category-specific; null for overall."
    )
    category_name: str | None = Field(
        None, description="Category name if category-specific; null or 'Overall' for overall."
    )
    savings_level_percent: int = Field(
        ..., description="User-selected savings level (0, 5, or 10)."
    )
    has_sufficient_history: bool = Field(
        ..., description="True if at least 3 completed months of history exist with spending."
    )
    historical_months: list[HistoricalMonthSpend] = Field(
        ..., description="Figures for each of the last 3 completed calendar months."
    )
    baseline_paise: int = Field(
        ..., description="Typical monthly baseline (median of raw monthly totals) in paise."
    )
    raw_median_paise: int = Field(
        ..., description="Median of trimmed monthly totals in paise."
    )
    savings_paise: int = Field(
        ..., description="Deducted savings amount in paise."
    )
    recommended_limit_paise: int = Field(
        ..., description="Recommended monthly limit in paise, rounded to nearest ₹100."
    )
    explanation: str = Field(
        ..., description="One-sentence explanation from Groq or deterministic template."
    )
    source: str = Field(
        ..., description="'ai' if explanation was generated by Groq, 'template_fallback' otherwise."
    )


class BudgetRecommendationDataResponse(_StrictSchema):
    """Standard envelope for recommendation response."""

    data: BudgetRecommendationResponse
