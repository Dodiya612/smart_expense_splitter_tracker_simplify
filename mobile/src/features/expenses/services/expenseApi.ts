/**
 * US-07 / US-09 / US-13 – Expense API service.
 *
 * This thin service layer wraps the HTTP client so the form and list hooks stay
 * framework-agnostic.
 *
 * - fetchExpenses(): Calls real FastAPI endpoint GET /api/v1/expenses with offset pagination.
 * - createExpense(): POST /api/v1/expenses with the Idempotency-Key header (T-45; was a stub).
 * - updateExpense(), deleteExpense(), undoDeleteExpense(): PATCH / DELETE / restore.
 *
 * The form's category ids ('food', …) are mapped to the server's category UUIDs
 * on the way out and back on the way in (utils/categoryIds.ts). The server sends
 * camelCase field names; the mapper also accepts snake_case.
 *
 * The idempotency key is a UUID generated by the caller (useExpenseForm) so
 * that a network retry never saves the same expense twice (US-07).
 */

import { fastApiClient } from '@/services/api/fastApiClient';
import { ApiError } from '@/services/api/types';
import {
  PAYMENT_MODES,
  type CreateExpensePayload,
  type Expense,
  type PaymentMode,
  type UpdateExpensePayload,
} from '../types';
import { fromServerCategoryId, toServerCategoryId } from '../utils/categoryIds';
import { buildCreateExpenseBody } from '../utils/expensePayload';

/** Generate a v4-like UUID without depending on `crypto.randomUUID` for RN compatibility. */
function generateUUID(): string {
  return 'xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx'.replace(/[xy]/g, (c) => {
    const r = (Math.random() * 16) | 0;
    const v = c === 'x' ? r : (r & 0x3) | 0x8;
    return v.toString(16);
  });
}

export function newIdempotencyKey(): string {
  return generateUUID();
}

// ── Backend Wire Types for /api/v1/expenses ──────────────────────────────────

export interface BackendExpenseItem {
  id: string;
  user_id: string;
  category_id: string;
  amount_minor: number;
  amount_paise?: number;
  description: string;
  expense_date: string;
  occurred_on?: string;
  notes?: string | null;
  merchant?: string | null;
  payment_mode?: string | null;
  receipt_id?: string | null;
  version: number;
  created_at: string;
  updated_at: string;
  deleted_at?: string | null;
}

/** The same expense with the camelCase names the server actually sends. */
export interface BackendExpenseItemCamel {
  id: string;
  userId?: string;
  categoryId?: string;
  amountMinor?: number;
  amountPaise?: number;
  description?: string;
  expenseDate?: string;
  occurredOn?: string;
  notes?: string | null;
  merchant?: string | null;
  paymentMode?: string | null;
  version?: number;
  createdAt?: string;
  updatedAt?: string;
}

export interface BackendExpenseListMeta {
  total: number;
  limit: number;
  offset: number;
  next_cursor?: string | null;
}

export interface BackendExpenseListResponse {
  data: BackendExpenseItem[];
  meta: BackendExpenseListMeta;
}

export interface FetchExpensesParams {
  limit?: number;
  offset?: number;
  categoryId?: string;
  from?: string;
  to?: string;
  query?: string;
  minAmount?: number;
  maxAmount?: number;
  paymentMode?: string;
}

export interface FetchExpensesResult {
  expenses: Expense[];
  total: number;
  limit: number;
  offset: number;
  hasMore: boolean;
  nextCursor?: string | null;
}

/**
 * Maps a backend ExpenseResponse to the mobile client's Expense domain model.
 * Preserves integer paise for monetary accuracy (NFR-M01).
 */
export function mapBackendExpenseToDomain(
  raw: BackendExpenseItem | BackendExpenseItemCamel
): Expense {
  const item = raw as Partial<BackendExpenseItem> & Partial<BackendExpenseItemCamel>;
  const rawMode = (item.payment_mode || item.paymentMode || '').toLowerCase();
  const paymentMode: PaymentMode = (PAYMENT_MODES as readonly string[]).includes(rawMode)
    ? (rawMode as PaymentMode)
    : 'other';
  const description = item.description;

  return {
    id: String(item.id),
    amountPaise:
      item.amount_paise ?? item.amountPaise ?? item.amount_minor ?? item.amountMinor ?? 0,
    categoryId: fromServerCategoryId(String(item.category_id || item.categoryId || 'other')),
    date: item.expense_date || item.occurred_on || item.expenseDate || item.occurredOn || '',
    paymentMode,
    notes: (item.notes && item.notes.trim()) ? item.notes : (description || ''),
    isRecurring: false,
    version: item.version ?? 1,
    createdAt: item.created_at || item.createdAt || new Date().toISOString(),
    updatedAt: item.updated_at || item.updatedAt || new Date().toISOString(),
    description,
    merchant: item.merchant ?? undefined,
  };
}

/**
 * Fetches personal expenses with offset-based pagination and optional filtering.
 * Uses the shared ApiClient instance via public fastApiClient.get<T>().
 */
export async function fetchExpenses({
  limit = 20,
  offset = 0,
  categoryId,
  from,
  to,
  query,
  minAmount,
  maxAmount,
  paymentMode,
}: FetchExpensesParams = {}): Promise<FetchExpensesResult> {
  const queryParams = new URLSearchParams();
  queryParams.set('limit', String(limit));
  queryParams.set('offset', String(offset));

  if (categoryId) {
    queryParams.set('category_id', categoryId);
  }
  if (from) {
    queryParams.set('from', from);
  }
  if (to) {
    queryParams.set('to', to);
  }
  if (query && query.trim()) {
    queryParams.set('q', query.trim());
  }
  if (typeof minAmount === 'number') {
    queryParams.set('min_amount', String(minAmount));
  }
  if (typeof maxAmount === 'number') {
    queryParams.set('max_amount', String(maxAmount));
  }
  if (paymentMode && paymentMode.trim()) {
    queryParams.set('payment_mode', paymentMode.trim());
  }

  const endpoint = `/api/v1/expenses?${queryParams.toString()}`;
  const raw = await fastApiClient.get<BackendExpenseListResponse>(endpoint);

  const rawItems = Array.isArray(raw?.data) ? raw.data : [];
  const meta = raw?.meta ?? {
    total: rawItems.length,
    limit,
    offset,
    next_cursor: null,
  };

  const expenses = rawItems.map(mapBackendExpenseToDomain);
  const total = typeof meta.total === 'number' ? meta.total : expenses.length;
  const hasMore = offset + expenses.length < total;

  return {
    expenses,
    total,
    limit: meta.limit ?? limit,
    offset: meta.offset ?? offset,
    hasMore,
    nextCursor: meta.next_cursor ?? null,
  };
}

// ── Create / update / delete ──────────────────────────────────────────────────

/**
 * POST /api/v1/expenses (T-45; replaces the T-19 stub). A retry with the same
 * idempotency key returns the expense saved the first time, never a second one.
 */
export async function createExpense(
  payload: CreateExpensePayload
): Promise<Expense> {
  const saveFailed = new ApiError(
    'CREATE_FAILED',
    'Could not save this expense. Your form has been kept – please try again.',
    true
  );
  let raw: { data?: BackendExpenseItemCamel } | undefined;
  try {
    raw = await fastApiClient.post<{ data: BackendExpenseItemCamel }>(
      '/api/v1/expenses',
      buildCreateExpenseBody(payload),
      { 'Idempotency-Key': payload.idempotencyKey }
    );
  } catch (err) {
    if (err instanceof ApiError) {
      throw err;
    }
    throw saveFailed;
  }
  if (!raw || !raw.data) {
    throw saveFailed;
  }
  return mapBackendExpenseToDomain(raw.data);
}

export async function updateExpense(
  id: string,
  payload: UpdateExpensePayload
): Promise<Expense> {
  const body = {
    amount_minor: payload.amountPaise,
    description: payload.notes || 'Expense',
    category_id: toServerCategoryId(payload.categoryId),
    expense_date: payload.date,
    payment_mode: payload.paymentMode,
    notes: payload.notes,
    version: payload.version,
  };
  const headers: Record<string, string> = {
    'If-Match': String(payload.version),
  };

  // US-34: never report an unconfirmed edit as saved. Any failure surfaces as a
  // retryable error so the form keeps its values and offers "Try again".
  const saveFailed = new ApiError(
    'UPDATE_FAILED',
    'Could not save your changes. Your form has been kept – please try again.',
    true
  );
  let raw: { data?: BackendExpenseItem } | undefined;
  try {
    raw = await fastApiClient.patch<{ data: BackendExpenseItem }>(
      `/api/v1/expenses/${id}`,
      body,
      headers
    );
  } catch (err) {
    if (err instanceof ApiError) {
      throw err;
    }
    throw saveFailed;
  }
  if (!raw || !raw.data) {
    throw saveFailed;
  }
  return mapBackendExpenseToDomain(raw.data);
}

export async function deleteExpense(id: string): Promise<void> {
  try {
    await fastApiClient.delete<void>(`/api/v1/expenses/${id}`);
  } catch (err) {
    if (err instanceof ApiError) {
      throw err;
    }
    throw new ApiError('DELETE_FAILED', 'Could not delete. Please try again.', true);
  }
}

export async function undoDeleteExpense(id: string): Promise<void> {
  try {
    await fastApiClient.post<void>(`/api/v1/expenses/${id}/restore`);
  } catch (err) {
    if (err instanceof ApiError) {
      throw err;
    }
  }
}

export async function updateGroupExpense(
  groupId: string,
  expenseId: string,
  payload: {
    description?: string;
    amountPaise?: number;
    categoryId?: string;
    expenseDate?: string;
    version?: number;
    splitMode?: string;
    participantUserIds?: string[];
    payments?: Record<string, number>;
  }
): Promise<any> {
  const body: Record<string, any> = {
    description: payload.description,
    amount_paise: payload.amountPaise,
    category_id: payload.categoryId,
    expense_date: payload.expenseDate,
    version: payload.version,
    split_mode: payload.splitMode,
    participant_user_ids: payload.participantUserIds,
    payments: payload.payments,
  };
  const headers: Record<string, string> = {};
  if (payload.version !== undefined) {
    headers['If-Match'] = String(payload.version);
  }
  return await fastApiClient.patch<any>(
    `/api/v1/groups/${groupId}/expenses/${expenseId}`,
    body,
    headers
  );
}

export async function deleteGroupExpense(
  groupId: string,
  expenseId: string,
  version?: number
): Promise<any> {
  const headers: Record<string, string> = {};
  if (version !== undefined) {
    headers['If-Match'] = String(version);
  }
  const queryStr = version !== undefined ? `?version=${version}` : '';
  return await fastApiClient.delete<any>(
    `/api/v1/groups/${groupId}/expenses/${expenseId}${queryStr}`,
    headers
  );
}

export async function fetchGroupHistory(groupId: string): Promise<any[]> {
  return await fastApiClient.get<any[]>(`/api/v1/groups/${groupId}/history`);
}

